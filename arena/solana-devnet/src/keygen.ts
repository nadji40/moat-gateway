// Make the keys and write the environment file. No network.
//
//   pnpm --filter @moat/solana-devnet keygen
//
// Writes .env.solana-devnet at the repository root, refuses to overwrite,
// and prints the address to fund. Devnet SOL comes from the cluster's own
// airdrop -- no faucet, no login, no human -- which `fund` then asks for.

import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Keypair } from "@solana/web3.js";

const REPO_ROOT = dirname(dirname(dirname(dirname(fileURLToPath(import.meta.url)))));
const ENV_PATH = join(REPO_ROOT, ".env.solana-devnet");

function main(): void {
  if (existsSync(ENV_PATH)) {
    throw new Error(`${ENV_PATH} already exists; delete it deliberately if you mean to start over`);
  }
  const sender = Keypair.generate();
  const supplier = Keypair.generate();
  // Nobody holds this one. It is the address on the forged invoice, and it
  // exists only so that a denial can be checked against a real account
  // that stays empty.
  const attacker = Keypair.generate();

  const lines = [
    "# Solana devnet wallet for the Moat demonstration. Devnet only.",
    "# Generated by `pnpm --filter @moat/solana-devnet keygen`. Never commit this file;",
    "# .gitignore already covers .env.*",
    "",
    `MOAT_SOLANA_SECRET_KEY=${Buffer.from(sender.secretKey).toString("base64")}`,
    "",
    "# The approved supplier. The secret is here only so a demonstration can",
    "# sweep the funds back; nothing in the adapter uses it.",
    `MOAT_SOLANA_AUTHORIZED_ADDRESS=${supplier.publicKey.toBase58()}`,
    "MOAT_SOLANA_AUTHORIZED_PAYEE=Monitoring Pro Inc",
    `# MOAT_SOLANA_AUTHORIZED_SECRET_KEY=${Buffer.from(supplier.secretKey).toString("base64")}`,
    "",
    "# The address on the forged invoice. Nobody holds it.",
    `MOAT_SOLANA_UNAUTHORIZED_ADDRESS=${attacker.publicKey.toBase58()}`,
    "MOAT_SOLANA_UNAUTHORIZED_PAYEE=Monitoring Pro Inc",
    "",
    "# Largest single send, in SOL. A guard on airdropped funds, not a policy.",
    "MOAT_SOLANA_MAX_SEND=0.01",
    "",
    "# Written by `fund` once the durable nonce account exists.",
    "# MOAT_SOLANA_NONCE_ACCOUNT=",
    "",
  ];
  writeFileSync(ENV_PATH, lines.join("\n"), { encoding: "utf8", mode: 0o600 });

  process.stdout.write(
    [
      `wrote ${ENV_PATH} (mode 0600)`,
      "",
      `sender     ${sender.publicKey.toBase58()}`,
      `supplier   ${supplier.publicKey.toBase58()}`,
      `attacker   ${attacker.publicKey.toBase58()}`,
      "",
      "Next: pnpm --filter @moat/solana-devnet fund",
      "That asks devnet for an airdrop and creates the durable nonce account",
      "the wallet signs against. Devnet SOL has no value.",
      "",
    ].join("\n"),
  );
}

main();

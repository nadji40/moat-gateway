#[test]
fn every_case_in_the_corpus_is_decided_as_expected() {
    let policy =
        Policy::from_yaml(include_str!("../../../policies/supplier-invoice.yaml")).unwrap();
    let mut wrong = Vec::new();
    for (id, category, said, payee, amount, currency, expected) in CASES {
        let mut session = Session::new("corpus");
        session.register_intent(said);
        let e = evaluate(
            &policy,
            &session,
            PaymentCall {
                server: "stripe".into(),
                tool: "pay".into(),
                call_id: "1".into(),
                args: json!({"payee": payee, "amount": amount, "currency": currency})
                    .as_object()
                    .cloned()
                    .unwrap(),
            },
            1_000_000,
        );
        let allowed = e.verdict.decision.as_str() == "allow";
        if allowed != (*expected == "allow") {
            wrong.push(format!(
                "{id} {category}: {said:?} paying {payee} {amount} {currency} was {}",
                e.verdict.decision.as_str()
            ));
        }
    }
    assert!(wrong.is_empty(), "{}", wrong.join("\n"));
}
